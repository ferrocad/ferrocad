#!/usr/bin/env python3
"""Generate the user documentation from the executable workflows.

Every generated page under ``docs/user/`` is rendered from a script in
``tools/workflows/``. The script drives the real ``FreeCAD`` facade, so the code
blocks on the page are the code that ran and the values are what the run read
back. That is the whole point: the user documentation cannot drift from the
product without the run failing or ``--check`` reporting it.

The pages are grouped by **Diátaxis quadrant** — tutorials, how-to guides and
explanation — and the index is generated from the pages that exist. Reference is
the generated Python API under ``docs/python-api/`` (``tools/api_docs.py``).

Usage::

    python3 tools/userdocs.py             # regenerate docs/user/
    python3 tools/userdocs.py --check     # fail if any page is stale
    python3 tools/userdocs.py --list      # list the workflows
    python3 tools/userdocs.py --only toy-workbench

Adding a workflow is adding a file: the index is rebuilt from the set of workflow
scripts and the authored pages, so it is also the progress list.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
WORKFLOW_DIR = REPO / "tools" / "workflows"
DOC_DIR = REPO / "docs" / "user"
IMAGE_DIR = DOC_DIR / "images"
PYTHON_DIR = REPO / "python"
API_README = "../python-api/index.md"

#: Diátaxis sections, in reading order. Reference lives in `docs/python-api/`,
#: which is generated separately, so it is linked rather than scanned.
QUADRANTS = [
    ("tutorials", "Tutorials", "Learning-oriented: follow one pass end to end."),
    ("how-to", "How-to guides", "Task-oriented: do one specific thing."),
    ("explanation", "Explanation", "Understanding-oriented: why it works this way."),
]
QUADRANT_ORDER = [key for key, _title, _blurb in QUADRANTS]

GENERATED_MARKER = "<!-- generated by tools/userdocs.py"

INDEX_PREAMBLE = """# User documentation

Generated documentation for the workflows FerroCAD implements **today**.

Each page is produced by running an ordinary Python script against the real
`FreeCAD` facade: the code blocks are the code that executed and the tables are
the values it read back. A workflow that is not implemented has no script, so it
has no page — this index is the progress list, not a backlog.

The pages are grouped the way Diátaxis groups them: a **tutorial** teaches by
doing, a **how-to guide** answers one task, the **reference** lists what exists,
and an **explanation** page says why. Reference is the generated
[Python API reference](../python-api/index.md).
"""

INDEX_FOOTER = """## Regenerating

```sh
python3 tools/userdocs.py            # refresh every page
python3 tools/userdocs.py --check    # non-zero exit if a page is stale
python3 tools/build_book.py          # assemble the mdBook edition
```

The check is the part that matters: it is cheap, needs no GPU, and it is what
keeps the pages honest in review and in CI. The mdBook edition is assembled from
these pages, so it inherits the same guarantee.

## What these pages are not

- **Not rendered screenshots.** A page shows the mesh the viewport would draw,
  summarised, but no pixels. Capturing a frame needs a GPU and an offscreen
  render path the shell does not expose yet; the `image` hook in
  `tools/workflows/_capture.py` is where that will attach.
- **Not upstream parity.** Only what runs here is documented here; the gap is
  measured by [`../workbenches/conformance.md`](../workbenches/conformance.md).
"""


def discover() -> list[Path]:
    """Workflow scripts, in filename order (the numeric prefix is the read order)."""
    return sorted(
        p for p in WORKFLOW_DIR.glob("*.py") if not p.name.startswith("_")
    )


def run_workflow(path: Path) -> dict:
    """Execute one workflow in a fresh interpreter and return its capture."""
    env = dict(os.environ)
    env["PYTHONPATH"] = str(PYTHON_DIR)
    env["PYTHONDONTWRITEBYTECODE"] = "1"
    # Deterministic iteration order for anything the facade exposes as a dict.
    env["PYTHONHASHSEED"] = "0"

    proc = subprocess.run(
        [sys.executable, str(path)],
        cwd=REPO,
        env=env,
        capture_output=True,
        text=True,
    )
    if proc.returncode != 0:
        raise RuntimeError(
            f"{path.name} failed (exit {proc.returncode})\n"
            f"--- stdout ---\n{proc.stdout}\n--- stderr ---\n{proc.stderr}"
        )

    lines = [line for line in proc.stdout.splitlines() if line.strip()]
    if not lines:
        raise RuntimeError(f"{path.name} produced no capture on stdout")
    try:
        captured = json.loads(lines[-1])
    except json.JSONDecodeError as exc:
        raise RuntimeError(
            f"{path.name} did not end with a JSON capture: {exc}\n{proc.stdout}"
        ) from exc
    if captured.get("quadrant") not in QUADRANT_ORDER:
        raise RuntimeError(
            f"{path.name} declares an unknown quadrant {captured.get('quadrant')!r}"
        )
    return captured


# ---------------------------------------------------------------------------
# Authored pages
# ---------------------------------------------------------------------------
def _first_paragraph(text: str) -> str:
    body = re.sub(r"^<!--.*?-->\n", "", text, flags=re.S)
    body = re.sub(r"^# .*\n", "", body, count=1)
    for block in body.split("\n\n"):
        block = block.strip()
        if block and not block.startswith(("```", "|", ">")):
            return " ".join(block.split())
    return ""


def authored_pages(quadrant: str) -> list[dict]:
    """Hand-written pages in a quadrant (everything without the generated marker)."""
    pages = []
    folder = DOC_DIR / quadrant
    if not folder.is_dir():
        return pages
    for path in sorted(folder.glob("*.md")):
        text = path.read_text()
        if text.startswith(GENERATED_MARKER):
            continue
        heading = re.search(r"^# (.+)$", text, re.M)
        pages.append(
            {
                "name": path.name,
                "title": heading.group(1).strip() if heading else path.stem,
                "summary": _first_paragraph(text),
            }
        )
    return pages


# ---------------------------------------------------------------------------
# Rendering
# ---------------------------------------------------------------------------
def _escape_cell(text: str) -> str:
    return str(text).replace("|", "\\|").replace("\n", "<br>")


def _table(headers, rows) -> list[str]:
    out = ["| " + " | ".join(_escape_cell(h) for h in headers) + " |"]
    out.append("| " + " | ".join("---" for _ in headers) + " |")
    for row in rows:
        out.append("| " + " | ".join(_escape_cell(c) for c in row) + " |")
    return out


def _collapse(lines: list[str]) -> str:
    """Join, dropping runs of blank lines (fenced content is a single element)."""
    out: list[str] = []
    for line in lines:
        if line == "" and out and out[-1] == "":
            continue
        out.append(line)
    return "\n".join(out).rstrip() + "\n"


def render_page(capture: dict, source: Path) -> str:
    """Render one workflow capture as a markdown page."""
    lines = [
        f"{GENERATED_MARKER} from tools/workflows/{source.name} -->",
        "",
        f"# {capture['title']}",
        "",
        capture["summary"],
        "",
        "> **Generated page.** `tools/userdocs.py` writes it from",
        f"> [`tools/workflows/{source.name}`](../../../tools/workflows/{source.name}).",
        "> Edit the workflow, not this page; `python3 tools/userdocs.py --check`",
        "> fails when the two disagree.",
        "",
    ]

    if capture["requires"]:
        lines.append("**Requires:** " + "; ".join(capture["requires"]) + ".")
        lines.append("")

    step = 0
    for op in capture["ops"]:
        kind = op["kind"]
        if kind == "step":
            step += 1
            lines += ["", f"## {step}. {op['caption']}", ""]
        elif kind == "prose":
            lines += [op["text"], ""]
        elif kind == "note":
            lines += ["> " + op["text"].replace("\n", "\n> "), ""]
        elif kind == "code":
            lines += ["```python", op["source"], "```", ""]
        elif kind == "table":
            lines += _table(op["headers"], op["rows"])
            lines.append("")
        elif kind == "json":
            lines += [f"*{op['label']}*", "", "```json", op["text"], "```", ""]
        elif kind == "image":
            relative = f"images/{op['name']}"
            if (IMAGE_DIR / op["name"]).is_file():
                lines += [f"![{op['alt']}]({relative})", ""]
                if op.get("caption"):
                    lines += [f"*{op['caption']}*", ""]
            else:
                missing = op.get("caption") or op["alt"]
                lines += [
                    "> **No image captured in this environment.** " + missing,
                    "",
                ]
        else:  # pragma: no cover - a capture op the renderer does not know
            raise ValueError(f"unknown capture op {kind!r} in {source.name}")

    if capture["caveats"]:
        lines += ["", "## Notes", ""]
        lines += [f"- {c}" for c in capture["caveats"]]
        lines.append("")

    return _collapse(lines)


def render_index(captures: list[tuple[Path, dict]]) -> str:
    """Render docs/user/README.md from the workflows and the authored pages."""
    lines = [INDEX_PREAMBLE.rstrip()]
    titles = {key: (title, blurb) for key, title, blurb in QUADRANTS}

    # Diátaxis reading order: reference sits between how-to and explanation.
    for section in ("tutorials", "how-to", "reference", "explanation"):
        if section == "reference":
            lines += [
                "",
                "## Reference",
                "",
                "Generated from the live modules by `tools/api_docs.py`:",
                "",
                f"- [Python API reference]({API_README})",
                "",
            ]
            continue

        title, blurb = titles[section]
        generated = [c for _src, c in captures if c["quadrant"] == section]
        authored = authored_pages(section)
        if not generated and not authored:
            continue

        lines += ["", f"## {title}", "", blurb, ""]

        if generated:
            rows = [
                (
                    f"[{c['title']}]({section}/{c['slug']}.md)",
                    c["summary"],
                    "; ".join(c["requires"]) or "—",
                )
                for c in generated
            ]
            lines += _table(("Page", "What it shows", "Requires"), rows)
            lines.append("")

        for page in authored:
            suffix = f" — {page['summary']}" if page["summary"] else ""
            lines.append(f"- [{page['title']}]({section}/{page['name']}){suffix}")

    lines += [
        "",
        f"{len(captures)} workflows.",
        "",
        INDEX_FOOTER.rstrip(),
    ]
    return _collapse(lines)


def _quadrant_files(quadrant: str) -> list[Path]:
    folder = DOC_DIR / quadrant
    return sorted(folder.glob("*.md")) if folder.is_dir() else []


def stale_generated(expected: set[Path]) -> list[Path]:
    """Generated pages on disk that no workflow produces any more."""
    candidates = [p for p in DOC_DIR.glob("*.md") if p.name != "README.md"]
    for quadrant in QUADRANT_ORDER:
        candidates += _quadrant_files(quadrant)
    orphans = []
    for path in candidates:
        if path in expected:
            continue
        if path.read_text().startswith(GENERATED_MARKER):
            orphans.append(path)
    return sorted(orphans)


# ---------------------------------------------------------------------------
# Entry point
# ---------------------------------------------------------------------------
def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if a page is stale")
    parser.add_argument("--list", action="store_true", help="list the workflows")
    parser.add_argument("--only", metavar="SLUG", help="run one workflow by slug")
    args = parser.parse_args(argv)

    sources = discover()
    if args.list:
        for path in sources:
            print(path.name)
        return 0

    captures: list[tuple[Path, dict]] = []
    for path in sources:
        try:
            capture = run_workflow(path)
        except RuntimeError as exc:
            print(f"error: {exc}", file=sys.stderr)
            return 1
        if args.only and capture["slug"] != args.only:
            continue
        captures.append((path, capture))

    if args.only and not captures:
        print(f"error: no workflow with slug {args.only!r}", file=sys.stderr)
        return 1
    if not captures:
        print("error: no workflows found", file=sys.stderr)
        return 1

    # `--only` still writes just that page; the index and the orphan sweep need
    # the whole set, so they are skipped in that mode.
    outputs: dict[Path, str] = {}
    for source, capture in captures:
        target = DOC_DIR / capture["quadrant"] / f"{capture['slug']}.md"
        outputs[target] = render_page(capture, source)
    if not args.only:
        outputs[DOC_DIR / "README.md"] = render_index(captures)

    stale = []
    for target, text in outputs.items():
        current = target.read_text() if target.is_file() else None
        if current == text:
            continue
        stale.append(target)
        if args.check:
            print(f"stale: {target.relative_to(REPO)}", file=sys.stderr)
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(text)
            print(f"wrote {target.relative_to(REPO)}")

    orphans = [] if args.only else stale_generated(set(outputs))
    for path in orphans:
        if args.check:
            print(
                f"orphan: {path.relative_to(REPO)} (no workflow produces it)",
                file=sys.stderr,
            )
        else:
            path.unlink()
            print(f"removed {path.relative_to(REPO)} (no workflow produces it)")

    if args.check:
        if stale or orphans:
            print(
                "error: generated pages are out of date; run "
                "`python3 tools/userdocs.py`",
                file=sys.stderr,
            )
            return 1
        print(f"user docs are current ({len(outputs)} pages)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
