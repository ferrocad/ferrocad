def _first_paragraph(text: str) -> str:
    body = re.sub(r"^<!--.*?-->\n", "", text, flags=re.S)
    body = re.sub(r"^# .*\n", "", body, count=1)
    for block in body.split("\n\n"):
        block = block.strip()
        if block and not block.startswith(("```", "|", ">")):
            return " ".join(block.split())
    return ""


def authored_pages(quadrant: str) -> list[dict]:
    """Hand-written pages in a quadrant (everything without the generated marker)."""
    pages = []
    folder = DOC_DIR / quadrant
    if not folder.is_dir():
        return pages
    for path in sorted(folder.glob("*.md")):
        text = path.read_text()
        if text.startswith(GENERATED_MARKER):
            continue
        heading = re.search(r"^# (.+)$", text, re.M)
        pages.append(
            {
                "name": path.name,
                "title": heading.group(1).strip() if heading else path.stem,
                "summary": _first_paragraph(text),
            }
        )
    return pages


# ---------------------------------------------------------------------------
# Rendering
# ---------------------------------------------------------------------------
def _escape_cell(text: str) -> str:
    return str(text).replace("|", "\\|").replace("\n", "<br>")


def _table(headers, rows) -> list[str]:
    out = ["| " + " | ".join(_escape_cell(h) for h in headers) + " |"]
    out.append("| " + " | ".join("---" for _ in headers) + " |")
    for row in rows:
        out.append("| " + " | ".join(_escape_cell(c) for c in row) + " |")
    return out


def _collapse(lines: list[str]) -> str:
    """Join, dropping runs of blank lines (fenced content is a single element)."""
    out: list[str] = []
    for line in lines:
        if line == "" and out and out[-1] == "":
            continue
        out.append(line)
    return "\n".join(out).rstrip() + "\n"


def render_page(capture: dict, source: Path) -> str:
    """Render one workflow capture as a markdown page."""
    lines = [
        f"{GENERATED_MARKER} from tools/workflows/{source.name} -->",
        "",
        f"# {capture['title']}",
        "",
        capture["summary"],
        "",
        "> **Generated page.** `tools/userdocs.py` writes it from",
        f"> [`tools/workflows/{source.name}`](../../../tools/workflows/{source.name}).",
        "> Edit the workflow, not this page; `python3 tools/userdocs.py --check`",
        "> fails when the two disagree.",
        "",
    ]

    if capture["requires"]:
        lines.append("**Requires:** " + "; ".join(capture["requires"]) + ".")
        lines.append("")

    step = 0
    for op in capture["ops"]:
        kind = op["kind"]
        if kind == "step":
            step += 1
            lines += ["", f"## {step}. {op['caption']}", ""]
        elif kind == "prose":
            lines += [op["text"], ""]
        elif kind == "note":
            lines += ["> " + op["text"].replace("\n", "\n> "), ""]
        elif kind == "code":
            lines += ["```python", op["source"], "```", ""]
        elif kind == "table":
            lines += _table(op["headers"], op["rows"])
            lines.append("")
        elif kind == "json":
            lines += [f"*{op['label']}*", "", "```json", op["text"], "```", ""]
        elif kind == "image":
            # Pages live in `docs/user/<quadrant>/`; the committed images live in
            # the sibling `docs/user/images/`.
            relative = f"../images/{op['name']}"
            if (IMAGE_DIR / op["name"]).is_file():
                lines += [f"![{op['alt']}]({relative})", ""]
                if op.get("caption"):
                    lines += [f"*{op['caption']}*", ""]
            else:
                missing = op.get("caption") or op["alt"]
                lines += [
                    "> **No image captured in this environment.** " + missing,
                    "",
                ]
        else:  # pragma: no cover - a capture op the renderer does not know
            raise ValueError(f"unknown capture op {kind!r} in {source.name}")

    if capture["caveats"]:
        lines += ["", "## Notes", ""]
        lines += [f"- {c}" for c in capture["caveats"]]
        lines.append("")

    return _collapse(lines)


def render_index(captures: list[tuple[Path, dict]]) -> str:
    """Render docs/user/README.md from the workflows and the authored pages."""
    lines = [INDEX_PREAMBLE.rstrip()]
    titles = {key: (title, blurb) for key, title, blurb in QUADRANTS}

    # Diátaxis reading order: reference sits between how-to and explanation.
    for section in ("tutorials", "how-to", "reference", "explanation"):
        if section == "reference":
            lines += [
                "",
                "## Reference",
                "",
                "Generated from the live modules by `tools/api_docs.py`:",
                "",
                f"- [Python API reference]({API_README})",
                "",
            ]
            continue

        title, blurb = titles[section]
        generated = [c for _src, c in captures if c["quadrant"] == section]
        authored = authored_pages(section)
        if not generated and not authored:
            continue

        lines += ["", f"## {title}", "", blurb, ""]

        if generated:
            rows = [
                (
                    f"[{c['title']}]({section}/{c['slug']}.md)",
                    c["summary"],
                    "; ".join(c["requires"]) or "—",
                )
                for c in generated
            ]
            lines += _table(("Page", "What it shows", "Requires"), rows)
            lines.append("")

        for page in authored:
            suffix = f" — {page['summary']}" if page["summary"] else ""
            lines.append(f"- [{page['title']}]({section}/{page['name']}){suffix}")

    lines += [
        "",
        f"{len(captures)} workflows.",
        "",
        INDEX_FOOTER.rstrip(),
    ]
    return _collapse(lines)


def _quadrant_files(quadrant: str) -> list[Path]:
    folder = DOC_DIR / quadrant
    return sorted(folder.glob("*.md")) if folder.is_dir() else []


def stale_generated(expected: set[Path]) -> list[Path]:
    """Generated pages on disk that no workflow produces any more."""
    candidates = [p for p in DOC_DIR.glob("*.md") if p.name != "README.md"]
    for quadrant in QUADRANT_ORDER:
        candidates += _quadrant_files(quadrant)
    orphans = []
    for path in candidates:
        if path in expected:
            continue
        if path.read_text().startswith(GENERATED_MARKER):
            orphans.append(path)
    return sorted(orphans)


# ---------------------------------------------------------------------------
# Image capture
# ---------------------------------------------------------------------------
#: The workspace tool that renders one spec into one PNG.
SNAPSHOT_PACKAGE = "ferrocad_snapshot"
SNAPSHOT_BIN = "ferrocad_snapshot"

#: The tool's exit code for "this machine has no GPU adapter".
SNAPSHOT_NO_ADAPTER = 3

#: The renderer's default size, mirrored here for manifest entries whose spec omits
#: one (`ferrocad_wgpu::snapshot::DEFAULT_SIZE`).
SNAPSHOT_DEFAULT_SIZE = [960, 600]

#: The committed record of which PNG belongs to which render spec.
MANIFEST_VERSION = 1


def _safe_image_name(name: str) -> str:
    """Reject a name that would write outside ``docs/user/images/``."""
    if (
        not name
        or name in (".", "..")
        or Path(name).name != name
        or "/" in name
        or "\\" in name
    ):
        raise RuntimeError(f"image name {name!r} must be a plain file name")
    if not name.endswith(".png"):
        raise RuntimeError(f"image name {name!r} must end in .png")
    return name


def _manifest_path() -> Path:
    """The committed image manifest (kept beside the PNGs)."""
    return IMAGE_DIR / "manifest.json"


def _canonical_spec(spec: dict) -> str:
    """The byte-stable form of a spec, so key order never changes the digest."""
    return json.dumps(spec, sort_keys=True, separators=(",", ":"), ensure_ascii=False)


def spec_digest(spec: dict) -> str:
    """A stable SHA-256 for one render spec."""
    return hashlib.sha256(_canonical_spec(spec).encode("utf-8")).hexdigest()


def png_digest(data: bytes) -> str:
    """The SHA-256 of a committed PNG."""
    return hashlib.sha256(data).hexdigest()


def _image_ops(captures: list[tuple[Path, dict]]):
    """Every ``image`` op with the workflow that produced it."""
    for source, capture in captures:
        for op in capture["ops"]:
            if op["kind"] == "image":
                yield source, capture, op


def expected_images(captures: list[tuple[Path, dict]]) -> dict[str, dict]:
    """The generated images the workflows describe, keyed by file name.

    An ``image`` op with no render spec is a manually supplied illustration: it is
    deliberately absent from the manifest, because the tool cannot reproduce it.
    """
    entries: dict[str, dict] = {}
    for _source, capture, op in _image_ops(captures):
        spec = op.get("spec")
        if not spec:
            continue
        name = _safe_image_name(op["name"])
        digest = spec_digest(spec)
        if name in entries:
            if entries[name]["spec_sha256"] != digest:
                raise RuntimeError(
                    f"image {name!r} is declared with two different render specs"
                )
            entries[name]["workflows"].add(capture["slug"])
            continue
        entries[name] = {
            "spec_sha256": digest,
            "size": [int(value) for value in spec.get("size", SNAPSHOT_DEFAULT_SIZE)],
            "workflows": {capture["slug"]},
        }
    for entry in entries.values():
        entry["workflows"] = sorted(entry["workflows"])
    return entries


def build_manifest(captures: list[tuple[Path, dict]], *, require_png: bool = True) -> dict:
    """The manifest a fresh capture would write, including the PNG digests."""
    entries: dict[str, dict] = {}
    for name, info in sorted(expected_images(captures).items()):
        target = IMAGE_DIR / name
        if not target.is_file():
            if require_png:
                raise RuntimeError(
                    f"{name} has a render spec but no committed PNG; run "
                    "`python3 tools/userdocs.py --capture`"
                )
            continue
        data = target.read_bytes()
        entries[name] = {
            **info,
            "png_sha256": png_digest(data),
            "bytes": len(data),
        }
    return {
        "version": MANIFEST_VERSION,
        "generator": "tools/userdocs.py",
        "images": entries,
    }


def write_manifest(captures: list[tuple[Path, dict]], *, require_png: bool = True) -> tuple[bool, int]:
    """Write the image manifest, atomically. Returns ``(changed, images)``."""
    manifest = build_manifest(captures, require_png=require_png)
    text = json.dumps(manifest, indent=2, sort_keys=True) + "\n"
    path = _manifest_path()
    if path.is_file() and path.read_text() == text:
        return False, len(manifest["images"])
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(f".{path.name}.tmp")
    try:
        temporary.write_text(text)
        os.replace(temporary, path)
    except OSError as exc:
        if temporary.exists():
            temporary.unlink()
        raise RuntimeError(f"cannot write {path.relative_to(REPO)}: {exc}") from exc
    return True, len(manifest["images"])


def load_manifest() -> dict | None:
    """Read the committed manifest, or ``None`` when no capture has run."""
    path = _manifest_path()
    if not path.is_file():
        return None
    try:
        data = json.loads(path.read_text())
    except json.JSONDecodeError as exc:
        raise RuntimeError(f"{path.relative_to(REPO)} is not valid JSON: {exc}") from exc
    if data.get("version") != MANIFEST_VERSION:
        raise RuntimeError(
            f"{path.relative_to(REPO)} has version {data.get('version')!r}; "
            f"expected {MANIFEST_VERSION}"
        )
    if not isinstance(data.get("images"), dict):
        raise RuntimeError(f"{path.relative_to(REPO)} has no images object")
    return data


def check_images(
    captures: list[tuple[Path, dict]], expected: dict[str, dict] | None = None
) -> list[str]:
    """Compare the workflows' specs and the committed PNGs with the manifest.

    This is the GPU-free half of the screenshot guarantee: it catches a changed
    camera or shape (the spec digest), a hand-edited or stale PNG (the byte digest),
    a missing image, and a manifest entry no workflow produces any more.
    """
    if expected is None:
        expected = expected_images(captures)
    manifest = load_manifest()
    if manifest is None:
        if not expected:
            return []
        return [
            "missing docs/user/images/manifest.json "
            "(run `python3 tools/userdocs.py --capture` or `--write-manifest`)"
        ]

    entries = manifest["images"]
    errors: list[str] = []
    for name, info in sorted(expected.items()):
        entry = entries.get(name)
        if entry is None:
            errors.append(
                f"missing manifest entry: {name} "
                "(run `python3 tools/userdocs.py --capture` or `--write-manifest`)"
            )
            continue
        if entry.get("spec_sha256") != info["spec_sha256"]:
            errors.append(
                f"stale spec: {name} (the workflow's render spec changed; "
                "run `python3 tools/userdocs.py --capture`)"
            )
            continue
        target = IMAGE_DIR / name
        if not target.is_file():
            errors.append(
                f"missing image: {name} (run `python3 tools/userdocs.py --capture`)"
            )
            continue
        if entry.get("png_sha256") != png_digest(target.read_bytes()):
            errors.append(
                f"stale image: {name} (the committed PNG does not match the manifest; "
                "run `python3 tools/userdocs.py --capture`)"
            )

    for name in sorted(set(entries) - set(expected)):
        errors.append(
            f"orphan manifest entry: {name} (no workflow produces it; "
            "run `python3 tools/userdocs.py --write-manifest`)"
        )
    return errors


def snapshot_binary(explicit: str | None = None) -> Path:
    """The snapshot renderer binary, built first so it cannot be stale.

    ``--snapshot-bin`` and ``FERROCAD_SNAPSHOT_BIN`` skip the build (the published
    docs workflow sets neither; ``--capture`` is a local tool).
    """
    for source, value in (
        ("--snapshot-bin", explicit),
        ("FERROCAD_SNAPSHOT_BIN", os.environ.get("FERROCAD_SNAPSHOT_BIN")),
    ):
        if not value:
            continue
        path = Path(value).expanduser()
        if not path.is_file():
            raise RuntimeError(f"{source}={value} is not a file")
        return path

    command = [
        "cargo",
        "build",
        "--offline",
        "-p",
        SNAPSHOT_PACKAGE,
    ]
    print("building the snapshot renderer: " + " ".join(command))
    proc = subprocess.run(command, cwd=REPO, capture_output=True, text=True)
    if proc.returncode != 0:
        raise RuntimeError(
            "could not build the snapshot renderer\n"
            f"--- stdout ---\n{proc.stdout}\n--- stderr ---\n{proc.stderr}"
        )
    path = REPO / "target" / "debug" / SNAPSHOT_BIN
    if not path.is_file():
        raise RuntimeError(f"cargo reported success but {path} does not exist")
    return path


def capture_images(captures: list[tuple[Path, dict]], binary: Path) -> tuple[int, int, bool]:
    """Render every ``image`` op's spec into ``docs/user/images/``.

    Returns ``(written, unchanged, degraded)``. ``degraded`` is true when the
    machine has no GPU adapter: the capture stops before touching any file, so the
    committed images survive and the normal gates still run.
    """
    pending = [
        (op, capture["slug"])
        for _source, capture in captures
        for op in capture["ops"]
        if op["kind"] == "image"
    ]
    if not pending:
        print("no images to capture")
        return 0, 0, False

    IMAGE_DIR.mkdir(parents=True, exist_ok=True)
    written = 0
    unchanged = 0
    for op, slug in pending:
        name = _safe_image_name(op["name"])
        spec = op.get("spec")
        if not spec:
            print(
                f"note: {name} ({slug}) has no render spec; leaving the committed "
                "image alone"
            )
            continue

        with tempfile.TemporaryDirectory(prefix="ferrocad-snapshot-") as tmp:
            spec_path = Path(tmp) / "spec.json"
            png_path = Path(tmp) / "out.png"
            spec_path.write_text(json.dumps(spec, indent=2, sort_keys=True) + "\n")
            proc = subprocess.run(
                [str(binary), str(spec_path), str(png_path)],
                cwd=REPO,
                capture_output=True,
                text=True,
            )
            if proc.returncode == SNAPSHOT_NO_ADAPTER:
                print(
                    "warning: no GPU adapter available; leaving docs/user/images/ "
                    f"untouched ({len(pending)} image(s) not captured). "
                    "The pages and `--check` only read the committed PNGs.",
                    file=sys.stderr,
                )
                return written, unchanged, True
            if proc.returncode != 0:
                raise RuntimeError(
                    f"snapshot render failed for {name} ({slug}, exit "
                    f"{proc.returncode})\n--- stdout ---\n{proc.stdout}\n"
                    f"--- stderr ---\n{proc.stderr}"
                )
            data = png_path.read_bytes()

        target = IMAGE_DIR / name
        shown = target.relative_to(REPO)
        if target.is_file() and target.read_bytes() == data:
            unchanged += 1
            print(f"unchanged {shown} ({len(data)} bytes)")
        else:
            # Write beside the target and rename, so an interrupted capture never
            # leaves a half-written PNG that a later `--check` would read.
            temporary = target.with_name(f".{name}.tmp")
            temporary.write_bytes(data)
            os.replace(temporary, target)
            written += 1
            print(f"wrote {shown} ({len(data)} bytes)")
    return written, unchanged, False


# ---------------------------------------------------------------------------
# Entry point
# ---------------------------------------------------------------------------
def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="fail if a page is stale")
    mode.add_argument(
        "--capture",
        action="store_true",
        help="render the workflows' image ops into docs/user/images/ (needs a GPU)",
    )
    mode.add_argument(
        "--write-manifest",
        action="store_true",
        help="adopt the existing PNGs into docs/user/images/manifest.json (no GPU)",
    )
    parser.add_argument("--list", action="store_true", help="list the workflows")
    parser.add_argument("--only", metavar="SLUG", help="run one workflow by slug")
    parser.add_argument(
        "--snapshot-bin",
        metavar="PATH",
        help="use this snapshot renderer instead of building the example",
    )
    args = parser.parse_args(argv)

    sources = discover()
    if args.list:
        for path in sources:
            print(path.name)
        return 0

    captures: list[tuple[Path, dict]] = []
    for path in sources:
        try:
            capture = run_workflow(path)
        except RuntimeError as exc:
            print(f"error: {exc}", file=sys.stderr)
            return 1
        if args.only and capture["slug"] != args.only:
            continue
        captures.append((path, capture))

    if args.only and not captures:
        print(f"error: no workflow with slug {args.only!r}", file=sys.stderr)
        return 1
    if not captures:
        print("error: no workflows found", file=sys.stderr)
        return 1

    if args.write_manifest:
        if args.only:
            print(
                "error: --write-manifest needs the whole workflow set; "
                "drop --only",
                file=sys.stderr,
            )
            return 1
        try:
            changed, count = write_manifest(captures)
        except (RuntimeError, OSError) as exc:
            print(f"error: {exc}", file=sys.stderr)
            return 1
        state = "updated" if changed else "unchanged"
        print(f"manifest: {state} ({count} image(s))")
        return 0

    if args.capture:
        try:
            binary = snapshot_binary(args.snapshot_bin)
            written, unchanged, degraded = capture_images(captures, binary)
        except (RuntimeError, OSError) as exc:
            print(f"error: {exc}", file=sys.stderr)
            return 1
        if not degraded:
            print(f"capture: {written} written, {unchanged} unchanged")
            if not args.only:
                try:
                    changed, count = write_manifest(captures)
                except (RuntimeError, OSError) as exc:
                    print(f"error: {exc}", file=sys.stderr)
                    return 1
                state = "updated" if changed else "unchanged"
                print(f"manifest: {state} ({count} image(s))")

    # `--only` still writes just that page; the index and the orphan sweep need
    # the whole set, so they are skipped in that mode.
    outputs: dict[Path, str] = {}
    for source, capture in captures:
        target = DOC_DIR / capture["quadrant"] / f"{capture['slug']}.md"
        outputs[target] = render_page(capture, source)
    if not args.only:
        outputs[DOC_DIR / "README.md"] = render_index(captures)

    stale = []
    for target, text in outputs.items():
        current = target.read_text() if target.is_file() else None
        if current == text:
            continue
        stale.append(target)
        if args.check:
            print(f"stale: {target.relative_to(REPO)}", file=sys.stderr)
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(text)
            print(f"wrote {target.relative_to(REPO)}")

    orphans = [] if args.only else stale_generated(set(outputs))
    for path in orphans:
        if args.check:
            print(
                f"orphan: {path.relative_to(REPO)} (no workflow produces it)",
                file=sys.stderr,
            )
        else:
            path.unlink()
            print(f"removed {path.relative_to(REPO)} (no workflow produces it)")

    image_errors: list[str] = []
    if args.check and not args.only:
        try:
            image_errors = check_images(captures)
        except (RuntimeError, OSError) as exc:
            print(f"error: {exc}", file=sys.stderr)
            return 1
    for message in image_errors:
        print(f"image: {message}", file=sys.stderr)

    if args.check:
        if stale or orphans or image_errors:
            if stale or orphans:
                print(
                    "error: generated pages are out of date; run "
                    "`python3 tools/userdocs.py`",
                    file=sys.stderr,
                )
            return 1
        images = len(expected_images(captures))
        print(f"user docs are current ({len(outputs)} pages, {images} generated image(s))")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
