"""User workflow: a document, typed and dynamic properties, and a rejected value.

This is the smallest end-to-end script. It is ordinary FreeCAD Python: nothing
here is FerroCAD-specific, so the same script is intended to run on upstream.
"""

from _capture import main

import FreeCAD

QUADRANT = "how-to"
SLUG = "documents-and-properties"
TITLE = "Create a document and edit properties"
SUMMARY = (
    "Open a document, add a typed length and an enumeration, write a value through "
    "each, and see the error an invalid enumeration value raises."
)
REQUIRES = ["the `FreeCAD` facade; no workbench module and no GPU"]


def run(cap):
    with cap.step("Create a document"):
        cap.prose(
            "`newDocument` registers the document with the application and makes it "
            "active. The registry lives in the Rust core, so the facade keeps no "
            "state of its own."
        )
        cap.exec("doc = FreeCAD.newDocument('Demo')")
        cap.result("Active document", FreeCAD.ActiveDocument.Name)
        cap.result("Open documents", sorted(FreeCAD.listDocuments()))

    with cap.step("Add properties"):
        cap.prose(
            "A feature object is created by type name. Properties are added one at a "
            "time and carry a group and a description, which is what a property "
            "editor shows. `App::PropertyLength` is a quantity, so it accepts a unit "
            "string and formats a value back with a unit."
        )
        cap.exec(
            """
            part = doc.addObject("App::FeaturePython", "Part")
            part.addProperty("App::PropertyLength", "Length", "Base", "Overall length")
            part.addProperty("App::PropertyEnumeration", "Finish", "Base", "Surface finish")
            part.Finish = ["As machined", "Anodised"]
            """
        )
        cap.exec(
            """
            part.Length = "10 mm"
            part.Finish = "Anodised"
            """
        )
        cap.result("part.Length", str(part.Length))
        cap.result("part.Finish", part.Finish)
        cap.result("Property types", [p for p in part.PropertiesList])

    with cap.step("An invalid value is rejected"):
        cap.prose(
            "The enumeration is a closed set. Assigning a value outside it raises "
            "`ValueError` and leaves the property unchanged; a script can rely on "
            "that instead of validating the set itself."
        )
        cap.exec(
            """
            try:
                part.Finish = "Bogus"
            except ValueError as exc:
                rejected = str(exc)
            """
        )
        cap.result("Error", rejected)
        cap.result("part.Finish is unchanged", part.Finish)

    with cap.step("What the properties describe"):
        cap.prose(
            "The document still stores values, not geometry. The box below uses the "
            "10 mm `Length`; the depth and height are illustrative, so the picture "
            "shows the scale the property describes."
        )
        cap.exec(
            """
            box_size = (float(part.Length), 20.0, 10.0)
            box_center = [value / 2.0 for value in box_size]
            span = max(box_size)
            box_eye = [
                box_center[0] - span * 0.8,
                box_center[1] - span * 1.8,
                box_center[2] + span * 1.5,
            ]
            """
        )
        cap.result("Box (length, depth, height)", box_size)
        cap.image(
            "documents-and-properties.png",
            "A 10 by 20 by 10 millimetre box drawn in the viewport",
            caption=(
                "The 10 mm `Length` from the properties above, drawn as a box; the "
                "depth and height are illustrative."
            ),
            shape={"box": {"size": list(box_size), "origin": [0.0, 0.0, 0.0]}},
            color=[0.55, 0.57, 0.60, 1.0],
            camera={
                "eye": box_eye,
                "target": box_center,
                "up": [0.0, 0.0, 1.0],
                "fov_y": 0.6,
            },
        )

    with cap.step("Close the document"):
        cap.prose("Closing unregisters the document from the application.")
        cap.exec("FreeCAD.closeDocument('Demo')")
        cap.result("Open documents", sorted(FreeCAD.listDocuments()))
        cap.note(
            "The values above are read from the live object, not from a fixture: this "
            "page is generated by running the script in `tools/workflows/`."
        )


if __name__ == "__main__":
    main(
        run,
        slug=SLUG,
        quadrant=QUADRANT,
        title=TITLE,
        summary=SUMMARY,
        requires=REQUIRES,
    )
